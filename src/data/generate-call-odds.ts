/**
 * Generates src/strategy/call-odds.ts: for every distinct roll (252) and
 * every call (17), the chance the Hammer takes the pencil when everyone
 * plays that call at a 3-player table. Played out by the engine with the
 * bots (their play, not their calls, so the table doesn't feed itself).
 * Monterey is played twice: by the default keep rules, and with the house
 * rule that lets a lone 3 or 4 be kept (CALL_ODDS_LONE_KEEP).
 *
 *   npm run generate:call-odds
 *
 * Forks one worker per CPU; takes a few minutes.
 */
import { fork } from 'child_process'
import { cpus } from 'os'
import { writeFileSync } from 'fs'
import { join } from 'path'
import { Call, Dice, HouseRules, applyAction, createGame, seeded } from '../engine'
import { ALL_CALLS } from '../strategy/bots'
import { playOutRound } from '../strategy/simulate'

const PLAYERS = 3
const SAMPLES = 2000
const OUT = join(__dirname, '../strategy/call-odds.ts')

const callKey = (c: Call) => (c.variant ? `${c.game} ${c.variant}` : c.game)

/** Every distinct roll, dice sorted low to high */
function hands(): Dice[] {
  const out: Dice[] = []
  for (let a = 1; a <= 6; a++)
    for (let b = a; b <= 6; b++)
      for (let c = b; c <= 6; c++)
        for (let d = c; d <= 6; d++)
          for (let e = d; e <= 6; e++) out.push([a, b, c, d, e] as Dice)
  return out
}

/** Per call, how often the Hammer holding `dice` loses when everyone plays it (common random numbers across calls) */
function lossRates(dice: Dice, calls: Call[], rules: Partial<HouseRules> = {}): number[] {
  const ids = Array.from({ length: PLAYERS }, (_, i) => (i === 0 ? 'me' : `p${i}`))
  return calls.map((call) => {
    let lost = 0
    for (let i = 0; i < SAMPLES; i++) {
      const g = createGame({
        players: ids.map((id) => ({ id, name: id })),
        hammer: 'me',
        source: seeded(i * 7919 + 17),
        rules: { ...rules, pencilsToLose: 1000 },
      })
      let s = applyAction({ ...g, dice: { ...g.dice, me: [...dice] } }, { type: 'call', player: 'me', call })
      s = applyAction(s, { type: 'accept', player: 'p1' })
      if (playOutRound(s).loser === 'me') lost++
    }
    return Math.round((lost / SAMPLES) * 1000)
  })
}

if (process.send) {
  // Worker: score the hands it's sent
  const monterey = ALL_CALLS.filter((c) => c.game === 'monterey')
  process.on('message', (keys: string[]) => {
    const out: Record<string, number[]> = {}
    keys.forEach((k) => {
      const dice = k.split('').map(Number) as Dice
      out[k] = [...lossRates(dice, ALL_CALLS), ...lossRates(dice, monterey, { montereyLoneKeep: true })]
    })
    process.send!(out, () => process.exit(0))
  })
} else {
  const keys = hands().map((d) => d.join(''))
  const n = cpus().length
  const result: Record<string, number[]> = {}
  let done = 0
  for (let w = 0; w < n; w++) {
    const child = fork(__filename, [], { execArgv: ['-r', 'sucrase/register/ts'] })
    child.on('message', (part: Record<string, number[]>) => {
      Object.assign(result, part)
      if (++done < n) return
      const width = ALL_CALLS.length
      const rows = keys.map((k) => `  '${k}': [${result[k].slice(0, width).join(', ')}],`).join('\n')
      const lone = keys.map((k) => `  '${k}': [${result[k].slice(width).join(', ')}],`).join('\n')
      writeFileSync(
        OUT,
        `// Generated by src/data/generate-call-odds.ts (npm run generate:call-odds). Don't edit by hand.

/** Table size and samples per hand and call */
export const CALL_ODDS_PLAYERS = ${PLAYERS}
export const CALL_ODDS_SAMPLES = ${SAMPLES}

/** The calls, in the order of each row below */
export const CALL_ODDS_CALLS = [${ALL_CALLS.map((c) => `'${callKey(c)}'`).join(', ')}]

/**
 * Per roll (dice sorted low to high): the chance the Hammer takes the
 * pencil when everyone plays each call, in tenths of a percent.
 */
export const CALL_ODDS: Record<string, number[]> = {
${rows}
}

/**
 * Monterey High and Low, per roll, under the house rule that lets a lone 3
 * or 4 be kept (docs/RULES.md §5), in tenths of a percent.
 */
export const CALL_ODDS_LONE_KEEP: Record<string, number[]> = {
${lone}
}
`
      )
      console.log(`Wrote ${keys.length} rolls × ${ALL_CALLS.length} calls to ${OUT}`)
    })
    child.send(keys.filter((_, i) => i % n === w))
  }
}

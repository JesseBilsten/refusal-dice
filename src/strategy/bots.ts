/**
 * A "solid" bot: reasonable, deterministic decisions for every phase of the
 * game. Calls and refusals come from how often each call loses when played
 * (call-odds.ts, generated by playing rounds with these bots); play is
 * heuristic but exact where it can be (keepOptions, tresAwayPutOut).
 * Strategy simulations play rounds with these bots, so simulated odds mean
 * "against (and as) a solid bot", not perfect play.
 *
 * Bots only look at what their player could see: their own dice before
 * play, and the visible dice during play.
 */

export const ALL_CALLS: Call[] = [
  ...KICKER_GAMES.flatMap((game) =>
    (['high', 'low'] as const).map((variant) => ({ game, variant }))
  ),
  ...SPECIALTY_GAMES.map((game) => ({ game })),
]

const callKey = (c: Call) => (c.variant ? `${c.game} ${c.variant}` : c.game)

/**
 * The chance the Hammer holding `dice` takes the pencil when everyone plays
 * `call` (3 players), from the generated table in call-odds.ts. Monterey
 * has its own figures when a lone 3 or 4 may be kept (`rules`).
 */
export function callLoss(dice: Dice, call: Call, rules?: KeepRules): number {
  const roll = [...dice].sort((a, b) => a - b).join('')
  const row = CALL_ODDS[roll]
  const i = CALL_ODDS_CALLS.indexOf(callKey(call))
  if (!row || i < 0) throw new Error(`No call odds for ${dice.join('')} ${callKey(call)}: run npm run generate:call-odds`)
  if (rules?.montereyLoneKeep && call.game === 'monterey') return CALL_ODDS_LONE_KEEP[roll][call.variant === 'high' ? 0 : 1] / 1000
  return row[i] / 1000
}

/** 0–1: how happy a player would be to play `call` with these dice (the chance of not losing it) */
export const callScore = (dice: Dice, call: Call, rules?: KeepRules): number => 1 - callLoss(dice, call, rules)

/**
 * Calls this close to the best (in chance of the pencil) are a toss-up:
 * call-odds.ts is good to about ±2 points per figure
 */
export const CALL_TIE = 0.03

/** Whether `dice` already make the game called (every roll plays a specialty game) */
export const makesCall = (dice: Dice, call: Call): boolean => !isKickerGame(call.game) || makesGame(dice, call.game)

/**
 * The call a bot Hammer makes; `except` is the refused game on a second
 * call. The call the roll loses least when everyone plays it, but among
 * calls within CALL_TIE of that, one the roll already makes: a game you
 * hold beats one you'd still have to make when the odds can't tell them
 * apart.
 */
export function chooseCall(dice: Dice, except?: string, rules?: KeepRules): Call {
  const ranked = ALL_CALLS.filter((c) => c.game !== except)
    .map((call) => ({ call, loss: callLoss(dice, call, rules) }))
    .sort((a, b) => a.loss - b.loss)
  const close = ranked.filter((o) => o.loss - ranked[0].loss <= CALL_TIE)
  return (close.find((o) => makesCall(dice, o.call)) ?? ranked[0]).call
}

/** An even share of the pencil at the table the call odds were played at */
const ACCEPT_LOSS = 1 / CALL_ODDS_PLAYERS

/**
 * A refuser bot accepts a call it would lose less often than an even share
 * of the table: refusing hands the Hammer a second call of their choosing.
 */
export const wouldAccept = (dice: Dice, call: Call, rules?: KeepRules): boolean =>
  callLoss(dice, call, rules) <= ACCEPT_LOSS

/* ── Playing ── */

/**
 * Play from the bottom (§4): whoever may roll holds the worst hand (or, in
 * a kicker game, hasn't made it yet), so roll with the exact best keep for
 * beating the next-worst hand (or just making the game, when that hand
 * missed too). Tied at the bottom with nobody else left to roll, take the
 * tie when that's at least as good as rolling (always with two players
 * left, where a tie means no pencil).
 */
function bottomAction(state: GameState, player: string): Action {
  const phase = state.phase
  if (phase.kind !== 'play') throw new Error('not in play')
  const dice = state.dice[player]
  const targetId = bottomTarget(state, player)!
  const goal = bottomGoal(phase.call, state.dice[targetId], phase.rolling[targetId].kept)
  const options = keepOptions(dice, 3 - phase.rolling[player].rollsUsed, goal, {
    locked: phase.rolling[player].kept,
    rules: state.rules,
  })
  if (!wouldLoseIfStopped(state, player) && (activeSeats(state).length === 2 || options[0].stand))
    return { type: 'stand', player }
  return { type: 'reroll', player, keep: options.find((o) => !o.stand)!.keep }
}

/**
 * What the worst hand needs: beat `target` (Razzle or a kicker), or make
 * the game when `target` missed too. `targetKept`: the positions the target
 * kept at their last roll, committed to their game.
 */
export function bottomGoal(call: Call, target: Dice, targetKept: number[] = []): Goal {
  if (call.game === 'razzle') return { kind: 'razzle', ...razzleScore(target) }
  const game = call.game as KickerGameId
  const them = evaluateKickerHand(target, game, call.variant!, targetKept)
  return them.made
    ? { kind: 'kicker', game, variant: call.variant!, total: them.kickerTotal }
    : { kind: 'make', game }
}

/**
 * Everyone who may act right now: one player, except in a kicker game
 * while several players are still making the game (they roll at once).
 * Empty between rounds.
 */
export function actors(state: GameState): string[] {
  const kind = state.phase.kind
  if (kind === 'roundOver' || kind === 'gameOver') return []
  if (kind === 'play') return rollers(state)
  const action = botAction(state)
  return 'player' in action ? [action.player] : []
}

/** The bot's action for `player`, who must be one of actors(state) */
export function botActionFor(state: GameState, player: string): Action {
  return state.phase.kind === 'play' ? bottomAction(state, player) : botAction(state)
}

/** The action the bot takes for whoever must act next. */
export function botAction(state: GameState): Action {
  const phase = state.phase
  switch (phase.kind) {
    case 'call':
      return {
        type: 'call',
        player: state.hammer,
        call: chooseCall(state.dice[state.hammer], undefined, state.rules),
      }
    case 'refusal': {
      const seats = refusalSeats(state)
      const player = phase.seat === 1 ? seats.first : seats.second!
      return {
        type: wouldAccept(state.dice[player], phase.call, state.rules) ? 'accept' : 'refuse',
        player,
      }
    }
    case 'secondCall':
      return {
        type: 'call',
        player: state.hammer,
        call: chooseCall(state.dice[state.hammer], phase.refused.game, state.rules),
      }
    case 'play':
      return bottomAction(state, rollers(state)[0])
    case 'tresAway': {
      const player = phase.turn
      const hand = phase.hands[player]
      const dice = state.dice[player]
      const inHand = [0, 1, 2, 3, 4].filter((i) => !hand.out.includes(i))
      // Can't lose: another player's put-out dice alone already score more than this whole hand
      const shown = (id: string) => tresAwayScore(phase.hands[id].out.map((i) => state.dice[id][i]))
      const safe = phase.order.some((id) => id !== player && shown(id) > tresAwayScore(dice))
      // Only the caller may put out past the caller's count: the rest stop there, lowest dice first,
      // and may put the held dice out on a later turn without rolling
      const choice = safe ? inHand : tresAwayPutOut(dice, inHand, { mayRoll: !hand.fresh })
      if (!choice.length) return { type: 'roll', player }
      const putOut = [...choice]
        .sort((a, b) => tresAwayScore([dice[a]]) - tresAwayScore([dice[b]]))
        .slice(0, tresAwayMaxPutOut(phase, player))
      return { type: 'putOut', player, dice: putOut.sort((a, b) => a - b) }
    }
    case 'boss': {
      if (phase.stage === 'bossRoll') {
        const dice = state.dice[phase.boss]
        const others = phase.players.filter((id) => id !== phase.boss).map((id) => state.dice[id])
        // Re-roll the low dice outside the hand, highest first back into the keep until what's kept still beats the table
        let weak = [0, 1, 2, 3, 4]
          .filter((i) => !phase.bossDice.includes(i) && dice[i] <= 3)
          .sort((a, b) => dice[a] - dice[b])
        const kept = () => [0, 1, 2, 3, 4].filter((i) => !weak.includes(i)).map((i) => dice[i])
        while (weak.length && bossKeepProblem(kept(), others)) weak = weak.slice(0, -1)
        return weak.length
          ? {
              type: 'reroll',
              player: phase.boss,
              keep: [0, 1, 2, 3, 4].filter((i) => !weak.includes(i)),
            }
          : { type: 'stand', player: phase.boss }
      }
      if (phase.stage === 'decide') {
        // Come up with two pair or better
        const strong = compareBoss(state.dice[phase.boss], [2, 2, 1, 1, 3]) >= 0
        return { type: strong ? 'comeUp' : 'dontComeUp', player: phase.boss }
      }
      const player = phase.waiting[0]
      const dice = state.dice[player]
      const hand = bossHand(dice)
      // Already beating someone who has finished? Stand. Otherwise keep the hand and roll the rest.
      const finished = phase.players.filter(
        (id) =>
          id !== player && id !== phase.boss && !phase.waiting.includes(id)
      )
      if (finished.some((id) => compareBoss(dice, state.dice[id]) > 0))
        return { type: 'stand', player }
      return { type: 'reroll', player, keep: hand.handDice }
    }
    case 'roundOver':
      return { type: 'nextRound' }
    case 'gameOver':
      throw new Error('The game is over')
  }
}
